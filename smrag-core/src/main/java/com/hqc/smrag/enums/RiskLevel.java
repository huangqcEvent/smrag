package com.hqc.smrag.enums;

import lombok.Getter;

/**
 * 风险等级枚举
 * <p>
 * 定义基金产品的风险等级，按照监管要求分为 5 级：
 * <ul>
 *     <li>R1：低风险，适合保守型投资者</li>
 *     <li>R2：中低风险，适合稳健型投资者</li>
 *     <li>R3：中风险，适合平衡型投资者</li>
 *     <li>R4：中高风险，适合进取型投资者</li>
 *     <li>R5：高风险，适合激进型投资者</li>
 * </ul>
 * <p>
 * 风险等级与投资者适当性匹配：
 * <ul>
 *     <li>保守型投资者：仅可购买 R1 产品</li>
 *     <li>稳健型投资者：可购买 R1、R2 产品</li>
 *     <li>平衡型投资者：可购买 R1、R2、R3 产品</li>
 *     <li>进取型投资者：可购买 R1、R2、R3、R4 产品</li>
 *     <li>激进型投资者：可购买所有产品</li>
 * </ul>
 *
 * @see com.hqc.smrag.entity.FundProduct 基金产品实体
 */
@Getter
public enum RiskLevel {

    /**
     * R1 级（低风险）
     * <p>
     * 风险极低，本金损失的可能性很小。
     * 例如：货币基金、短期理财债券型基金。
     */
    R1("低风险"),

    /**
     * R2 级（中低风险）
     * <p>
     * 风险较低，本金损失的可能性较小。
     * 例如：普通债券型基金。
     */
    R2("中低风险"),

    /**
     * R3 级（中风险）
     * <p>
     * 风险中等，本金可能受到一定损失。
     * 例如：混合型基金、可转债基金。
     */
    R3("中风险"),

    /**
     * R4 级（中高风险）
     * <p>
     * 风险较高，本金可能受到较大损失。
     * 例如：偏股型基金、指数基金。
     */
    R4("中高风险"),

    /**
     * R5 级（高风险）
     * <p>
     * 风险极高，本金可能遭受重大损失。
     * 例如：股票型基金、衍生品基金。
     */
    R5("高风险");

    /**
     * 等级描述
     */
    private final String desc;

    RiskLevel(String desc) {
        this.desc = desc;
    }
}